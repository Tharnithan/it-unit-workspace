import test from 'node:test';
import assert from 'node:assert/strict';
import {createApp} from '../src/app.js';
import {seed} from '../src/store.js';
test('ended tasks enforce permissions, month boundaries, pagination, reopening and deletion',async t=>{
 const db=seed();db.tasks=[];
 const server=createApp({db,save(){}}).listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));t.after(()=>server.close());
 const base=`http://127.0.0.1:${server.address().port}/api`;
 const call=async(path,token,method='GET',body)=>{const r=await fetch(base+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body?JSON.stringify(body):undefined});return {status:r.status,data:await r.json()}};
 const login=async username=>(await call('/login',null,'POST',{username,password:'ITunit-demo-2026!'})).data.token;
 const sdd=await login('itunit1'),employee=await login('itunit2'),other=await login('itunit3'),admin=await login('admin');
 for(const [id,assignee,at] of [['a','u1','2026-09-30T18:29:00Z'],['b','u1','2026-09-30T18:31:00Z'],['c','u2','2026-10-01T00:00:00Z']])db.tasks.push({id,assignee,title:'Task '+id,division:'Metrology',status:'Completed',completedAt:at,resolution:'Fixed cable',updates:[],events:[],progress:100});
 db.tasks.push({...db.tasks[0],id:'deleted',deleted:true},{...db.tasks[0],id:'active',status:'Assigned',completedAt:null});
 assert.equal((await call('/tasks/ended')).status,401);
 assert.deepEqual((await call('/tasks/ended',employee)).data.tasks.map(t=>t.id),['b','a']);
 assert.deepEqual((await call('/tasks/ended',other)).data.tasks.map(t=>t.id),['c']);
 assert.equal((await call('/tasks/ended',sdd)).data.total,3);
 assert.equal((await call('/tasks/ended',admin)).data.total,3);
 assert.deepEqual((await call('/tasks/ended?month=2026-10',employee)).data.tasks.map(t=>t.id),['b']);
 assert.equal((await call('/tasks/ended?search=cable',employee)).data.total,2);
 assert.equal((await call('/tasks/ended?search=missing',employee)).data.total,0);
 assert.deepEqual((await call('/tasks/ended?offset=1&limit=1',sdd)).data.tasks.map(t=>t.id),['b']);
 for(const query of ['month=2026-13','offset=-1','limit=101','limit=abc'])assert.equal((await call('/tasks/ended?'+query,sdd)).status,400);
 assert.equal((await call('/tasks/b',employee,'PATCH',{status:'Assigned',note:'recheck'})).status,403);
 assert.equal((await call('/tasks/b',sdd,'PATCH',{status:'Assigned',note:'recheck'})).status,200);
 assert.equal((await call('/tasks/ended',employee)).data.total,1);
 assert.equal((await call('/tasks/a',admin,'DELETE')).status,200);
 assert.equal((await call('/tasks/ended',employee)).data.total,0);
});
